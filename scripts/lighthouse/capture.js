#!/usr/bin/env node
/**
 * Rebuild the Lighthouse fixtures from the live site — `npm run capture:lighthouse`.
 *
 * Each fixture under tests/lighthouse/fixtures/ is a live search route's own
 * rendered markup: the `.iwac-search-shell` fragment (heading, noscript, mount
 * root, skeleton and the bootstrap JSON with its server-rendered first page
 * of results), the header search form the theme prints on every page, and the
 * `window.IWAC_HEADER_SEARCH` blob Module.php injects beside it — lifted from
 * the page, not restated, so the fixture cannot describe markup the module
 * never printed. Only the module's asset URLs are rewritten, to this
 * checkout's `asset/` files, so the gate measures the tree under review.
 *
 * The first page arrives in `initial_response`, which is what lets these
 * pages render real results with no Typesense behind them: the client seeds
 * its results from it, and what it still asks for on load (the year histogram,
 * the tab counts) scripts/lighthouse/server.js answers with empty pages, while
 * the gate counts the round trips. Thumbnails stay `/files/<tier>/…` paths;
 * the server answers them with the placeholders beside the fixtures.
 *
 * Re-capture deliberately — the hits are a snapshot of the live index, and a
 * new snapshot moves the baseline — then run `npm run check:lighthouse -- --update`.
 */

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const FIXTURES = join(ROOT, 'tests', 'lighthouse', 'fixtures');
const ORIGIN = 'https://islam.zmo.de';

/** Fixture name → the live English route it is captured from. */
export const SOURCES = {
  search: '/s/westafrica/search',
  everything: '/s/westafrica/search/everything',
};

/** Undo the escaping Laminas' escapeHtmlAttr applies to attribute values. */
function unescapeAttr(value) {
  return value.replace(/&#x([0-9a-f]+);/gi, (_, hex) => String.fromCodePoint(parseInt(hex, 16)));
}

/** The module's asset URLs, pointed at this checkout instead. */
function localAssets(html) {
  return html.replace(/\/modules\/IwacSearch\/(asset\/[^"'?]+)(\?v=[^"']*)?/g, '/$1');
}

/** The substring from `start` through the end of the element that opens there. */
function elementAt(html, start, tag) {
  const open = new RegExp(`<${tag}\\b|</${tag}>`, 'g');
  open.lastIndex = start;
  let depth = 0;
  for (let m = open.exec(html); m; m = open.exec(html)) {
    depth += m[0].startsWith('</') ? -1 : 1;
    if (depth === 0) return html.slice(start, m.index + m[0].length);
  }
  throw new Error(`unclosed <${tag}> at ${start}`);
}

function pick(html, marker, tag, what) {
  const at = html.indexOf(marker);
  if (at < 0) throw new Error(`no ${what} in the live page`);
  return elementAt(html, html.lastIndexOf(`<${tag}`, at), tag);
}

async function capture(name, route) {
  const response = await fetch(`${ORIGIN}${route}`);
  if (!response.ok) throw new Error(`${route}: HTTP ${response.status}`);
  const html = await response.text();

  const version = /\/modules\/IwacSearch\/asset\/[^"]+\?v=([0-9.]+)/.exec(unescapeAttr(html))?.[1];
  const shell = pick(html, 'class="iwac-search-shell"', 'div', 'search shell');
  // The bootstrap is a sibling of the mount root, inside the shell.
  if (!/<script type="application\/json" id="iwac-(search|federated)-state-/.test(shell)) {
    throw new Error(`${route}: the shell carries no bootstrap JSON`);
  }
  if (!shell.includes('"initial_response"') && !shell.includes('"tabs"')) {
    throw new Error(`${route}: no server-rendered first page — the fixture would need Typesense`);
  }
  const form = pick(html, 'data-iwac-header-search', 'form', 'header search form');
  const blob = /window\.IWAC_HEADER_SEARCH = [^\n]*/.exec(html)?.[0];
  if (!blob) throw new Error(`${route}: no IWAC_HEADER_SEARCH blob`);

  const page = [
    '<!doctype html>',
    '<html lang="en">',
    '<head>',
    '    <meta charset="utf-8">',
    '    <meta name="viewport" content="width=device-width, initial-scale=1">',
    `    <title>IwacSearch ${name} fixture</title>`,
    `    <!-- GENERATED by scripts/lighthouse/capture.js from ${ORIGIN}${route}`,
    `         (module ${version ?? 'unknown'}); never edit by hand. -->`,
    '    <link rel="stylesheet" href="/asset/css/iwac-search.css">',
    '    <link rel="stylesheet" href="/asset/dist/iwac-search.css">',
    '    <script defer src="/asset/dist/iwac-search.js"></script>',
    '    <script defer src="/asset/dist/iwac-search-header.js"></script>',
    `    <script>${localAssets(unescapeAttr(blob))}</script>`,
    '</head>',
    '<body>',
    '    <header class="main-header__search-form">',
    `        ${unescapeAttr(form)}`,
    '    </header>',
    '    <main>',
    localAssets(shell),
    '    </main>',
    '</body>',
    '</html>',
    '',
  ].join('\n');
  writeFileSync(join(FIXTURES, `${name}.html`), page);
  console.log(`✓ ${name}.html from ${route} (module ${version ?? 'unknown'}, ${page.length} B)`);
}

for (const [name, route] of Object.entries(SOURCES)) await capture(name, route);
